/**
 * Source Attribution for TheervuAI
 *
 * Provides a clear taxonomy distinguishing verified official information
 * from AI-generated guidance. This is critical for user trust and
 * zero-fabrication compliance.
 *
 * Attribution levels:
 * - VERIFIED_OFFICIAL: Sourced from .gov.in / .nic.in with recent verification date
 * - VERIFIED_INSTITUTIONAL: Sourced from statutory body (UIDAI, EPFO, etc.)
 * - SYSTEM_GUIDANCE: AI-generated guidance, not tied to a specific official source
 * - USER_PROVIDED: Information the user themselves entered
 * - REQUIRES_CONFIRMATION: Information that may be outdated or location-dependent
 */

// ─── Types ────────────────────────────────────────────────────────────────────

export type SourceTier =
  | 'VERIFIED_OFFICIAL'
  | 'VERIFIED_INSTITUTIONAL'
  | 'SYSTEM_GUIDANCE'
  | 'USER_PROVIDED'
  | 'REQUIRES_CONFIRMATION'

export type FreshnessStatus = 'fresh' | 'recently_verified' | 'review_due' | 'unknown'

export interface SourceRecord {
  title: string
  url: string
  department: string
  authority: string
  state: 'All India' | string
  tier: SourceTier
  lastVerifiedAt: string | null
  reviewDueAt?: string | null
  freshnessStatus: FreshnessStatus
  notes?: string
}

export interface AttributionBadge {
  label: string
  description: string
  tier: SourceTier
  color: 'green' | 'blue' | 'amber' | 'gray' | 'red'
  icon: string // emoji or icon name hint for UI
}

// ─── Domain Classification ────────────────────────────────────────────────────

const CENTRAL_GOV_DOMAINS = [
  'gov.in', 'nic.in', 'india.gov.in', 'mygov.in', 'pgportal.gov.in',
]
const STATE_GOV_PATTERNS = [/\.[a-z]{2}\.gov\.in$/, /\.gov\.[a-z]{2}\.in$/]
const INSTITUTIONAL_DOMAINS = [
  'uidai.gov.in', 'epfo.gov.in', 'utiitsl.com', 'protean-tinpan.com',
  'passportindia.gov.in', 'parivahan.gov.in', 'incometax.gov.in',
  'nsp.gov.in', 'myaadhaar.uidai.gov.in',
]

/**
 * Classifies a URL into a source tier based on its domain.
 */
export function classifySourceTier(url: string): SourceTier {
  try {
    const parsed = new URL(url)
    const hostname = parsed.hostname.toLowerCase()

    if (INSTITUTIONAL_DOMAINS.some((d) => hostname === d || hostname.endsWith(`.${d}`))) {
      return 'VERIFIED_INSTITUTIONAL'
    }

    if (CENTRAL_GOV_DOMAINS.some((d) => hostname === d || hostname.endsWith(`.${d}`))) {
      return 'VERIFIED_OFFICIAL'
    }

    if (STATE_GOV_PATTERNS.some((p) => p.test(hostname))) {
      return 'VERIFIED_OFFICIAL'
    }

    return 'REQUIRES_CONFIRMATION'
  } catch {
    return 'REQUIRES_CONFIRMATION'
  }
}

// ─── Freshness Calculation ────────────────────────────────────────────────────

const FRESH_THRESHOLD_DAYS = 30
const RECENTLY_VERIFIED_THRESHOLD_DAYS = 90

/**
 * Calculates the freshness status of a source based on last verification date.
 */
export function calculateFreshness(lastVerifiedAt: string | null): FreshnessStatus {
  if (!lastVerifiedAt) return 'unknown'

  const verifiedDate = new Date(lastVerifiedAt)
  if (isNaN(verifiedDate.getTime())) return 'unknown'

  const daysSince = (Date.now() - verifiedDate.getTime()) / (1000 * 60 * 60 * 24)

  if (daysSince <= FRESH_THRESHOLD_DAYS) return 'fresh'
  if (daysSince <= RECENTLY_VERIFIED_THRESHOLD_DAYS) return 'recently_verified'
  return 'review_due'
}

