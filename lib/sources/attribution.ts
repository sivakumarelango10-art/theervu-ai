/**
 * Returns a UI-ready attribution badge for a source tier.
 */
export function getAttributionBadge(tier: SourceTier): AttributionBadge {
  return TIER_BADGES[tier]
}

/**
 * Formats a source record into a human-readable attribution string.
 * Safe for rendering in UI or including in AI responses.
 */
export function formatSourceAttribution(source: SourceRecord): string {
  const badge = TIER_BADGES[source.tier]
  const freshLabel = {
    fresh: '✓ Verified recently',
    recently_verified: '✓ Verified within 90 days',
    review_due: '⚠ May require re-verification',
    unknown: 'Verification date unknown',
  }[source.freshnessStatus]

  return `${badge.icon} ${badge.label}: ${source.title} — ${source.department} (${source.authority}) — ${freshLabel}`
}

/**
 * Builds a SourceRecord from a CivicService for AI response attribution.
 */
export function buildSourceRecord(params: {
  title: string
  url: string
  department: string
  authority: string
  state?: string
  lastVerifiedAt?: string
  notes?: string
}): SourceRecord {
  const tier = classifySourceTier(params.url)
  const freshnessStatus = calculateFreshness(params.lastVerifiedAt || null)

  return {
    title: params.title,
    url: params.url,
    department: params.department,
    authority: params.authority,
    state: params.state || 'All India',
    tier,
    lastVerifiedAt: params.lastVerifiedAt || null,
    freshnessStatus,
    notes: params.notes,
  }
}
